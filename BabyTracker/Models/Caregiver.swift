// MARK: - Invite

/// Invite links generated by an admin. One-time use, expire after 7 days.
@Model
final class CaregiverInvite {
    @Attribute(.unique) var id: UUID
    var babyID: UUID
    var createdByID: UUID
    var role: CaregiverRole
    var code: String            // 8-char alphanumeric code
    var expiresAt: Date
    var usedAt: Date?
    var usedByID: UUID?
    var syncStatus: SyncStatus
    var remoteID: String?

    var isExpired: Bool { Date() > expiresAt }
    var isUsed: Bool { usedAt != nil }
    var isValid: Bool { !isExpired && !isUsed }

    init(babyID: UUID, createdByID: UUID, role: CaregiverRole) {
        self.id = UUID()
        self.babyID = babyID
        self.createdByID = createdByID
        self.role = role
        self.code = CaregiverInvite.generateCode()
        self.expiresAt = Calendar.current.date(byAdding: .day, value: 7, to: Date())!
        self.syncStatus = .pending
    }

    private static func generateCode() -> String {
        let chars = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789"  // no ambiguous chars
        return String((0..<8).map { _ in chars.randomElement()! })
    }
}
