import Foundation
import SwiftData

@Model
final class Caregiver {
    @Attribute(.unique) var id: UUID
    var displayName: String
    @Attribute(.externalStorage) var photoData: Data?
    var role: CaregiverRole
    var supabaseUserID: String?     // nil for anonymous / not yet synced
    var isCurrentDevice: Bool       // true for the logged-in user on this device
    var joinedAt: Date
    var syncStatus: SyncStatus
    var remoteID: String?
    var updatedAt: Date

    init(id: UUID = UUID(), displayName: String, role: CaregiverRole = .admin, isCurrentDevice: Bool = false) {
        self.id = id
        self.displayName = displayName
        self.role = role
        self.isCurrentDevice = isCurrentDevice
        self.joinedAt = Date()
        self.syncStatus = .pending
        self.updatedAt = Date()
    }
}

enum CaregiverRole: String, Codable, CaseIterable {
    case admin      // full access: add/edit/delete babies and entries
    case caregiver  // can add/edit entries; cannot add/delete babies or manage caregivers
    case viewer     // read-only

    var displayName: String {
        switch self {
        case .admin: return "Admin"
        case .caregiver: return "Caregiver"
        case .viewer: return "Viewer"
        }
    }

    var description: String {
        switch self {
        case .admin: return "Full access including managing babies and caregivers"
        case .caregiver: return "Can log feedings, sleep, diapers, and health entries"
        case .viewer: return "Can view all entries but cannot add or edit"
        }
    }

    // Permission helpers — enforced in ViewModels and in Supabase RLS
    var canAddEntry: Bool { self == .admin || self == .caregiver }
    var canEditEntry: Bool { self == .admin || self == .caregiver }
    var canDeleteEntry: Bool { self == .admin }
    var canManageBabies: Bool { self == .admin }
    var canManageCaregivers: Bool { self == .admin }
}

